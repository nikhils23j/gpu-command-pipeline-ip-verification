"""Bug-injection (mutation) campaign.

For each BUG_* define in the RTL (plus a bug-free baseline):
  * pure-SV bench, SV_SEEDS seeds x 5000 cycles
  * cocotb directed tests (one run) + test_random for RAND_SEEDS seeds x 2000 cycles
and record which checks caught it. Writes results/mutation.json + results/mutation.md.
"""
import json
import sys
import time

from common import BUILD, RESULTS, build, build_sv, run, run_sv, tool_versions

BUGS = {
    "BUG_SKID_DUP": "skid entry not cleared when it moves to main (command duplicated)",
    "BUG_ROB_NOFULL": "issue ignores ROB-full (overwrites an un-retired slot)",
    "BUG_OUT_NOT_HELD": "output register reloads while stalled",
    "BUG_ADDS_CARRY": "saturating add uses unsigned carry for overflow",
    "BUG_SRA_LOGICAL": "SRA implemented as logical shift",
    "BUG_DIV_SHORT": "divider runs 15 iterations instead of 16",
    "BUG_FLUSH_DIV": "flush does not cancel an in-flight divide",
    "BUG_MINMAX_UNSIGNED": "MIN/MAX compare unsigned",
    "BUG_MAC_FLAG": "MAC overflow flag ignores carry out of the add",
}
DIRECTED = ["test_directed_ops", "test_full_throughput", "test_backpressure_freeze",
            "test_flush_corners", "test_reset_midstream", "test_div_chain"]
SV_SEEDS = range(1, 9)
RAND_SEEDS = range(1, 4)


def kind(msg):
    for k in ("PROTOCOL", "SCOREBOARD", "WATCHDOG", "DRAIN"):
        if k in msg:
            return k
    if "nowhere to put them" in msg:
        return "CAPACITY"
    return "OTHER"


def campaign(bug):
    defines = [bug] if bug else []
    row = {"bug": bug or "none (bug-free RTL)", "description": BUGS.get(bug, "baseline")}
    sim = BUILD / f"sv_mut_{bug or 'none'}"
    build_sv(sim, defines)
    sv = [run_sv(sim, s, 5000) for s in SV_SEEDS]
    row["sv_caught"] = [s for s, (p, _) in zip(SV_SEEDS, sv) if not p]
    row["sv_first_msg"] = next((m for p, m in sv if not p), "")

    runner, bdir = build("mut", defines={d: 1 for d in defines})
    n, nf, fails = run(runner, bdir, "directed", testcase=DIRECTED)
    row["directed_caught"] = sorted(fails)
    row["directed_msgs"] = fails
    caught = []
    for s in RAND_SEEDS:
        n, nf, f = run(runner, bdir, f"rand{s}", testcase="test_random",
                       env={"N2_SEED": str(s), "N2_CYCLES": "2000"})
        if nf:
            caught.append(s)
            row.setdefault("random_first_msg", next(iter(f.values())))
    row["random_caught"] = caught
    msgs = [row["sv_first_msg"]] + list(fails.values()) + [row.get("random_first_msg", "")]
    row["check_types"] = sorted({kind(m) for m in msgs if m})
    row["detected"] = bool(row["sv_caught"] or row["directed_caught"] or row["random_caught"])
    return row


def main():
    RESULTS.mkdir(exist_ok=True)
    t0 = time.time()
    rows = []
    for bug in [None] + list(BUGS):
        r = campaign(bug)
        rows.append(r)
        print(f"{r['bug']:22s} SV {len(r['sv_caught'])}/{len(SV_SEEDS)}  directed "
              f"{len(r['directed_caught'])}/{len(DIRECTED)}  random {len(r['random_caught'])}/{len(RAND_SEEDS)}"
              f"  {r['check_types']}", flush=True)
    base, bugs = rows[0], rows[1:]
    ok = (not base["detected"]) and all(r["detected"] for r in bugs)
    out = {"tools": tool_versions(), "wall_seconds": round(time.time() - t0, 1),
           "sv_seeds": list(SV_SEEDS), "sv_cycles": 5000, "random_seeds": list(RAND_SEEDS),
           "random_cycles": 2000, "directed_tests": DIRECTED,
           "bugs_detected": sum(r["detected"] for r in bugs), "bugs_total": len(bugs),
           "baseline_false_alarms": base["detected"], "rows": rows}
    (RESULTS / "mutation.json").write_text(json.dumps(out, indent=1))
    md = ["# Bug-injection results (generated by scripts/mutate.py)", "",
          f"{out['bugs_detected']}/{out['bugs_total']} injected bugs detected; "
          f"bug-free baseline false alarms: {base['detected']}", "",
          f"| bug | what it breaks | SV seeds failing (/{len(SV_SEEDS)}) | cocotb directed tests failing (/{len(DIRECTED)}) "
          f"| cocotb random seeds failing (/{len(RAND_SEEDS)}) | caught by |",
          "|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| `{r['bug']}` | {r['description']} | {len(r['sv_caught'])} | "
                  f"{len(r['directed_caught'])} ({', '.join(t.replace('test_', '') for t in r['directed_caught']) or '-'}) | "
                  f"{len(r['random_caught'])} | {', '.join(r['check_types']) or '-'} |")
    (RESULTS / "mutation.md").write_text("\n".join(md) + "\n")
    print(f"\nMUTATION {'PASS' if ok else 'FAIL'}: {out['bugs_detected']}/{out['bugs_total']} bugs caught, "
          f"baseline clean={not base['detected']}, {out['wall_seconds']}s")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
