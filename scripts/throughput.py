"""Measure throughput (ops/cycle) and latency vs. output stall rate, divide mix
and ROB depth. Writes results/throughput.json + results/throughput.md."""
import json
import sys
import time

from common import BUILD, RESULTS, build, run, tool_versions

DEPTHS = [4, 8, 16]


def main():
    RESULTS.mkdir(exist_ok=True)
    t0 = time.time()
    tmp = BUILD / "tput.jsonl"
    if tmp.exists():
        tmp.unlink()
    ok = True
    for d in DEPTHS:
        runner, bdir = build(f"tput_d{d}", parameters={"ROB_DEPTH": d})
        n, nf, fails = run(runner, bdir, "tput", module="test_throughput",
                           env={"N2_TPUT_OUT": str(tmp), "N2_ROB_DEPTH": str(d)})
        ok &= (n == 1 and nf == 0)
        print(f"ROB_DEPTH={d}: {'PASS' if nf == 0 else fails}", flush=True)
    rows = [json.loads(x) for x in tmp.read_text().splitlines()]
    out = {"tools": tool_versions(), "all_checks_passed": ok, "wall_seconds": round(time.time() - t0, 1),
           "method": "in_valid always 1; out_ready random with prob ready_p; 50 warm-up cycles then "
                     "a 4000-cycle window; ops_per_cycle = outputs accepted in window / 4000; "
                     "latency = cycle accepted at input -> cycle accepted at output",
           "command": "python scripts/throughput.py", "rows": rows}
    (RESULTS / "throughput.json").write_text(json.dumps(out, indent=1))
    md = ["# Throughput (generated by scripts/throughput.py)", "", out["method"], ""]
    for mix in sorted({r["div_mix"] for r in rows}):
        md += [f"## divide mix {int(mix * 100)}%", "",
               "| out_ready prob | " + " | ".join(f"ROB={d} ops/cycle" for d in DEPTHS) +
               " | fast-op latency min/avg (ROB=8) | div latency min/avg (ROB=8) |",
               "|---|" + "---|" * (len(DEPTHS) + 2)]
        for p in sorted({r["ready_p"] for r in rows}, reverse=True):
            sel = {r["rob_depth"]: r for r in rows if r["div_mix"] == mix and r["ready_p"] == p}
            r8 = sel[8]
            dl = f"{r8['div_lat_min']}/{r8['div_lat_avg']}" if r8["div_lat_min"] is not None else "-"
            md.append(f"| {p} | " + " | ".join(f"{sel[d]['ops_per_cycle']:.3f}" for d in DEPTHS) +
                      f" | {r8['fast_lat_min']}/{r8['fast_lat_avg']} | {dl} |")
        md.append("")
    (RESULTS / "throughput.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
